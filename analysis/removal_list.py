"""B5 step 1: FRA removal-tagged spells split by condition (oracle text) and cost, printed for Akshin's review before any test.
Unconditional: destroys / exiles / -X/-X / bounces any creature. Damage: N damage to a creature (kills by toughness).
Conditional: restricted target (tapped, attacking, flying, power or mana value cap, ...) or needs your creature (fight, bite).

    MTGA_COMPANION_DATA=<repo>/data env -C <repo> uv run python analysis/removal_list.py > docs/removal-list-FRA.md
"""
import json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from companion import DATA_DIR  # noqa: E402
from companion.advisor_v2 import config  # noqa: E402

COND = r"(tapped|attacking|blocking|with flying|with power \d or (less|greater)|power \d or (less|greater)|mana value \d or (less|greater)" \
       r"|toughness \d or (less|greater)|that was dealt damage|token|legendary|multicolou?red|enchanted creature|an opponent sacrifices)"
BITE = r"(fights|deals damage equal to its power|deals damage equal to (that|target) creature's power)"
DMG = r"deals? (\d+|x) damage to (any target|target creature|target attacking|each creature)"

# Lead's corrections where the regex misreads the card (a mode or a cost matched, colour hosers missed); marked * in the table.
# "shrink" = -X/-X or toughness-capped like damage; "sweeper" = hits every creature.
FIX = {"Essence Burn": "conditional", "Refute Destiny": "conditional", "Terminal Criticism": "conditional",
       "Prophesied End": "unconditional", "Vindictive Triumph": "unconditional", "Silence the Echo": "unconditional",
       "Stingerquill Charm": "damage", "Wrath of the Bloodmane": "damage", "Craftwork Crusher": "damage",
       "Last Gasp": "damage", "Theorix Charm": "damage", "Proft, Sinister Mastermind": "damage",
       "The Echoverse Fulcrum": "sweeper", "Overwrite the Multiverse": "sweeper", "Kindred Judgment": "sweeper",
       "Rise of the Deathbringer": "sweeper", "Clash of Elements": "tempo", "Plan for All Outcomes": "tempo",
       "Living Library": "conditional"}
# Akshin 2026-11-06: planeswalkers are not counted as removal; Clash and Plan are "tempo" (owner may redraw the card).
DROP = {"Garruk, Veiled Butcher", "Ajani Unrelenting", "Chandra, Torch of Defiance"}

cards = {}
for v in json.loads((DATA_DIR / "Sets" / "FRA_PremierDraft_All_Data.json").read_text())["card_ratings"].values():
    n = v["name"]
    if n in DROP or "Land" in (v.get("types") or []) or "removal" not in config.tags(v, "FRA"):
        continue
    a = v["deck_colors"]["All Decks"]
    if n in cards and cards[n]["s"] >= a["samples"]:
        continue
    t = re.sub(r"\([^)]*\)", "", v.get("oracle_text") or "").lower()
    cls = "bite/fight" if re.search(BITE, t) else "conditional" if re.search(COND, t) else \
          "damage" if re.search(DMG, t) else "unconditional"
    cls = FIX.get(n, cls) + ("*" if n in FIX and FIX[n] != cls else "")
    cmc = int(v.get("cmc") or 0)
    cards[n] = dict(s=a["samples"], g=a["gihwr"] or 0, cmc=cmc, band="<=2" if cmc <= 2 else "3-4" if cmc <= 4 else "5+",
                    cls=cls, cre="Creature" in v["types"], text=" ".join(t.split())[:160])

print(f"# FRA removal list for review (B5), {len(cards)} cards\n")
print("Generated by analysis/removal_list.py from the dataset's removal tag (with manual tag_fixes) and oracle text. "
      "Correct the class column where it is wrong; strike cards that are not removal.\n")
print("| Card | cmc | band | class | creature | GIH WR | text |\n|---|---|---|---|---|---|---|")
for n, c in sorted(cards.items(), key=lambda kv: (kv[1]["cls"], kv[1]["cmc"], kv[0])):
    print(f"| {n} | {c['cmc']} | {c['band']} | {c['cls']} | {'y' if c['cre'] else ''} | {c['g']:.1f} | {c['text'].replace('|', '/')} |")
counts = {}
for c in cards.values():
    k = (c["cls"].rstrip("*"), c["band"]); counts[k] = counts.get(k, 0) + 1
print("\n| class | <=2 | 3-4 | 5+ |\n|---|---|---|---|")
for k in ("unconditional", "damage", "conditional", "bite/fight", "sweeper", "tempo"):
    print(f"| {k} | " + " | ".join(str(counts.get((k, b), 0)) for b in ("<=2", "3-4", "5+")) + " |")
(Path(__file__).parent / "out" / "removal_classes_FRA.json").write_text(json.dumps(
    {n: dict(cls=c["cls"].rstrip("*"), cmc=c["cmc"], band=c["band"]) for n, c in cards.items()}, indent=1))
